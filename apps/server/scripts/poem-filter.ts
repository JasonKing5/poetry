interface RawRecord {
  title: string;
  dynasty: string;
  author: string;
  content: string;
}

function processFile(filePath: string, dynastyTag: string, outputList: RawRecord[]) {
  if (!fs.existsSync(filePath)) return;

  const fileContent = fs.readFileSync(filePath, 'utf-8');
  const records: RawRecord[] = parse(fileContent, {
    columns: ['title', 'dynasty', 'author', 'content'],
    skip_empty_lines: true,
    relax_quotes: true,
    from_line: 2,
  });

  for (const record of records) {
    let { title, author, content } = record;
    if (!title || !content) continue;

    title = title.trim();
    author = author ? author.trim() : '无名氏';

    content = content
      .trim()
      .replace(/^["']/, '')
      .replace(/["'\\]*$/, '')
      .replaceAll('\\r', '').replaceAll('\\n', '').replaceAll('\r', '').replaceAll('\n', '')
      .replaceAll('\\"', '"')
      .trim();

    if (content.length < 4) continue;

    outputList.push({ title, author, dynasty: dynastyTag, content });
  }
}

