// ==========================================
// 5.5 标题规范化
// ==========================================
// CSV 中的标题可能带有选集前缀、编号后缀等，需要规范化为标准标题

// 已知标题别名表：CSV 标题 → 标准标题（与 MANDATORY_MAPPING/ANTHOLOGY_MAPPING 一致）
const TITLE_ALIASES: Record<string, string> = {
  '望庐山瀑布水': '望庐山瀑布',
};

function normalizeTitle(title: string): string {
  // 去掉选集/乐府前缀：如 "鼓吹曲辞 将进酒" → "将进酒"
  title = title.replace(/^(?:鼓吹曲辞|乐府古题序|乐府杂曲|新乐府|相和歌辞|清商曲辞|舞曲歌辞|琴曲歌辞|杂曲歌辞|杂歌谣辞|近代曲辞)\s+/, '');

  // 去掉「X首 其Y」后缀（仅匹配含「首」的格式，避免误删诗序号）
  // 如 "绝句四首 其三" → "绝句", "望庐山瀑布水二首 其二" → "望庐山瀑布水"
  title = title.replace(/[\s　]*(?:第[一二三四五六七八九十百]+[首]|[一二三四五六七八九十]+首)(?:[\s　]*[（(]?(?:其|之)[一二三四五六七八九十]+[)）]?)?$/, '');
  // 去掉括号内的「（其X）」后缀：如 "四时田园杂兴（其一）" → "四时田园杂兴"
  // 不处理非括号形式（如 "己亥杂诗 其五" 应保留原样）
  title = title.replace(/[\s　]*[（(](?:其|之)[一二三四五六七八九十]+[)）]?$/, '');

  // 去掉描述性后缀：如 "水调歌头丙辰中秋，欢饮达旦..." → "水调歌头"
  // 仅匹配已知的干支纪年后缀（不包括己亥/乙卯等，避免误删「己亥杂诗」等标题）
  title = title.replace(/[\s,，]*(?:丙辰|壬戌|癸丑).*/, '');

  // 空格 ↔ 中点统一：如 "念奴娇 赤壁怀古" → "念奴娇·赤壁怀古"
  // 排除第二部分为纯数字/序号的情况（如 "己亥杂诗 三一五"）
  if (/^[\u4e00-\u9fff]{2,5}\s+[\u4e00-\u9fff]/.test(title) && !title.includes('·')) {
    const parts = title.split(/\s+/);
    if (parts.length === 2 && parts[0].length >= 2 && parts[0].length <= 5 && parts[1].length >= 2 && parts[1].length <= 8
      && !/^[一二三四五六七八九十百千万零两]/.test(parts[1])) {
      title = parts[0] + '·' + parts[1];
    }
  }

  // 应用已知别名（在所有规范化之后，处理如 "望庐山瀑布水" → "望庐山瀑布"）
  return TITLE_ALIASES[title] || title;
}

interface PoemScore {
  textbook: number;
  anthology: number;
  famousLines: number;
  authorTier: number;
  styleVariety: number;
  lengthFit: number;
  crossRef: number;
  total: number;
}

interface ScoredPoem {
  title: string;
  author: string;
  dynasty: string;
  content: string;
  tags: string[];
  score: PoemScore;
}

interface AuthorScore {
  poemCount: number;
  avgScore: number;
  textbookCount: number;
  anthologyCount: number;
  tierWeight: number;
  total: number;
}

interface ScoredAuthor {
  name: string;
  dynasty: string;
  description: string;
  score: AuthorScore;
}

